#!/usr/bin/env node
/**
 * Builds src/data/words.ts for The Daily Five.
 *
 *   answers  common five-letter words, shuffled once with a fixed seed so the
 *            daily order never changes between builds
 *   allowed  every five-letter lowercase word the system dictionary knows,
 *            plus the answers
 *
 * Sources: Google's 10,000 most common English words (Josh Kaufman's list, no swears)
 * and the macOS system dictionary at /usr/share/dict/words (Webster's 2nd, public domain).
 * Run: node scripts/build-words.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const COMMON_URL = "https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-no-swears.txt";
const SEED = 20261024;

const res = await fetch(COMMON_URL);
if (!res.ok) throw new Error(`HTTP ${res.status} fetching the common-word list`);
const common = (await res.text()).split("\n").map((w) => w.trim());

const dictionary = new Set(
  readFileSync("/usr/share/dict/words", "utf8")
    .split("\n")
    .filter((w) => /^[a-z]{5}$/.test(w)),
);

const isPlural = (w) => w.endsWith("s") && !w.endsWith("ss") && dictionary.has(w.slice(0, 4)) === false ? false : w.endsWith("s") && !w.endsWith("ss");
const answers = common.filter((w) => /^[a-z]{5}$/.test(w) && dictionary.has(w) && !isPlural(w));

// Fixed-seed shuffle (mulberry32 + Fisher–Yates) so day N is always the same word.
let t = SEED;
const rand = () => {
  t += 0x6d2b79f5;
  let r = Math.imul(t ^ (t >>> 15), 1 | t);
  r = (r + Math.imul(r ^ (r >>> 7), 61 | r)) ^ r;
  return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
};
for (let i = answers.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [answers[i], answers[j]] = [answers[j], answers[i]];
}

const allowed = [...new Set([...dictionary, ...answers])].sort();
const out = `// Generated by scripts/build-words.mjs. Do not edit by hand.
// ${answers.length} answers in fixed daily order, ${allowed.length} allowed guesses.
export const answers = "${answers.join("")}";
export const allowed = "${allowed.join("")}";
`;
writeFileSync(new URL("../src/data/words.ts", import.meta.url), out);
console.log(`answers ${answers.length}, allowed ${allowed.length}`);
console.log("first ten days:", answers.slice(0, 10).join(" "));
